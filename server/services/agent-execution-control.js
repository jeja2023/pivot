'use strict';

const CONTROL_CODES = new Set(['AGENT_APPROVAL_REQUIRED', 'AGENT_APPROVAL_STALE', 'AGENT_APPROVAL_EXPIRED',
    'AGENT_RUN_CANCELLED', 'AGENT_RUN_PAUSED', 'AGENT_RUN_LEASE_LOST', 'AGENT_USER_REVOKED', 'AGENT_DISCOVERY_SCOPE_REVOKED',
    'KNOWLEDGE_SOURCE_UNAVAILABLE', 'KNOWLEDGE_SCOPE_DENIED', 'AGENT_BUDGET_EXCEEDED', 'AGENT_BUDGET_PERSIST_FAILED',
    'AGENT_FINALIZATION_REQUIRED', 'AGENT_NO_PROGRESS', 'AGENT_TIMEOUT']);

function isExecutionControlError(error) { return CONTROL_CODES.has(error?.code); }

module.exports = { isExecutionControlError };
