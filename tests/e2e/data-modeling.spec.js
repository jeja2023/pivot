/* global window */
'use strict';

const { test, expect } = require('@playwright/test');
const path = require('node:path');
const fs = require('node:fs/promises');

test('数据建模工作区通过真实表单完成草稿编辑、冲突保留和移动端布局', async ({ page }) => {
    test.setTimeout(120000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto('/chat', { waitUntil: 'domcontentloaded' });
    if (await page.locator('#username').isVisible()) {
        await page.locator('#username').fill('admin');
        await page.locator('#password').fill(process.env.DEFAULT_ADMIN_PASSWORD || 'E2eAdmin123');
        await page.locator('#auth-submit').click();
    }
    await expect(page.locator('#auth-container')).toBeHidden({ timeout: 15000 });
    await page.evaluate(() => window.Pivot.moduleApi('workspaces.navigation').openAppsWorkbench?.());
    await expect(page.locator('#apps-workbench-modal')).toBeVisible({ timeout: 15000 });
    await page.evaluate(async () => { await window.Pivot.loadScriptOnce('/chat/apps-workbench-data-analysis.js'); await window.Pivot.legacy.showDataAnalysisApp({ tab: 'overview' }); });
    await page.locator('#data-analysis-file').setInputFiles({ name: 'bi-model-orders.csv', mimeType: 'text/csv', buffer: Buffer.from('订单号,明细号,金额,地区\na,1,100.25,北区\na,2,99.75,北区\nb,1,50.00,南区\n', 'utf8') });
    await expect(page.locator('#data-analysis-dataset-table-body')).toContainText('bi-model-orders', { timeout: 20000 });
    await page.locator('[data-data-analysis-tab="modeling"]').click();
    await expect(page.locator('#modeling-list')).toBeVisible();
    await page.locator('[data-modeling-action="create"]').click();
    const form = page.locator('#modeling-dialog-form');
    await form.locator('[name="modeling_name"]').fill('浏览器订单模型');
    await form.locator('[name="modeling_description"]').fill('订单明细金额与订单数');
    await form.locator('[name="modeling_businessOwner"]').fill('订单业务负责人');
    await form.locator('[name="modeling_maintenanceContact"]').fill('订单维护联系人');
    await form.locator('[name="modeling_factDatasetId"]').selectOption({ label: 'bi-model-orders' });
    await form.locator('[type="submit"]').click();
    await expect(page.locator('#modeling-title')).toHaveText('浏览器订单模型');
    await page.locator('[data-modeling-action="node"]').click();
    await form.locator('[name="modeling_grainDescription"]').fill('一条订单商品明细');
    await form.locator('[name="modeling_grainKeys"]').selectOption(['c_1', 'c_2']);
    await form.locator('[type="submit"]').click();
    await expect(page.locator('#modeling-save-state')).toHaveText('未保存');
    await page.locator('[data-modeling-action="save"]').click();
    await expect(page.locator('#modeling-save-state')).toHaveText('已保存');
    await page.locator('[data-modeling-action="open-semantics"]').click();
    await expect(page.locator('#modeling-drawer')).toBeVisible();
    await page.locator('[data-modeling-action="dimension"]').click();
    await form.locator('[name="modeling_name"]').fill('地区');
    await form.locator('[name="modeling_fieldKey"]').selectOption('c_4');
    await form.locator('[type="submit"]').click();
    await page.locator('[data-modeling-action="metric"]').click();
    await form.locator('[name="modeling_name"]').fill('实付金额');
    await form.locator('[name="modeling_description"]').fill('订单明细实付金额合计，固定人民币。');
    await form.locator('[name="modeling_fieldKey"]').selectOption('c_3');
    await form.locator('[name="modeling_currencyMode"]').selectOption('fixed');
    await form.locator('[type="submit"]').click();
    await page.locator('[data-modeling-action="save"]').click();
    await expect(page.locator('#modeling-save-state')).toHaveText('已保存');
    await expect(page.locator('#modeling-content')).toContainText('实付金额');
    await page.locator('[data-modeling-action="check"]').click();
    await expect(page.locator('#modeling-content')).toContainText('完整检查通过', { timeout: 20000 });
    await page.locator('[data-modeling-action="publish"]').click();
    await form.locator('[name="modeling_confirm"]').check();
    await form.locator('[type="submit"]').click();
    await expect(page.locator('#modeling-version')).toContainText('发布 v1');
    await page.locator('[data-modeling-action="analyze"]').click();
    await page.locator('#modeling-query-mode').selectOption('published');
    await page.locator('#modeling-query-dimensions').selectOption({ label: '地区' });
    await page.locator('#modeling-query-metrics').selectOption({ label: '实付金额' });
    await page.locator('[data-modeling-action="run-published"]').click();
    await expect(page.locator('#modeling-run-result')).toContainText('250.00', { timeout: 20000 });
    const initialRun = await page.evaluate(() => window.Pivot.legacy.PivotDataAnalysis.modeling.state.run.id);
    await page.locator('[data-modeling-action="run-published"]').click();
    await expect(page.locator('#modeling-run-result')).toContainText('复用相同数据与口径的已验证结果', { timeout: 20000 });
    expect(await page.evaluate(() => window.Pivot.legacy.PivotDataAnalysis.modeling.state.run.id)).not.toBe(initialRun);
    const cacheArtifacts = path.resolve(__dirname, '../../output/bi-modeling'); await fs.mkdir(cacheArtifacts, { recursive: true });
    await page.screenshot({ path: path.join(cacheArtifacts, 'result-cache-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#modeling-run-result').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(cacheArtifacts, 'result-cache-mobile.png'), fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator('[data-modeling-action="chart-result"]').click();
    await form.locator('[type="submit"]').click();
    await expect(page.locator('#modeling-consumer-result .pivot-echart-block')).toBeVisible();
    await page.locator('[data-modeling-action="pivot-result"]').click();
    await expect(page.locator('#modeling-consumer-result')).toContainText('250.00', { timeout: 20000 });
    await page.locator('[data-modeling-action="save-view"]').click();
    await form.locator('[name="modeling_viewName"]').fill('浏览器地区金额视图');
    await form.locator('[type="submit"]').click();
    await expect(page.locator('#data-analysis-modeling-dialog')).toBeHidden();
    const download = page.waitForEvent('download');
    await page.locator('[data-modeling-action="export-csv"]').click();
    const csv = await download;
    expect(csv.suggestedFilename()).toMatch(/\.csv$/);
    const stream = await csv.createReadStream(); let csvText = '';
    for await (const chunk of stream) csvText += chunk.toString('utf8');
    expect(csvText).toContain('250.00'); expect(csvText).toContain('完整结果'); expect(csvText).toContain('原计算时间'); expect(csvText).toContain('本次重新核对当前权限');
    await page.locator('[data-modeling-action="close-drawer"]').click();
    await expect(page.locator('#modeling-drawer')).toBeHidden();
    const graphNode = page.locator('[data-modeling-graph-node]').first();
    await graphNode.focus(); await page.keyboard.press('ArrowRight');
    await expect(page.locator('#modeling-save-state')).toHaveText('未保存');
    await page.locator('[data-modeling-action="save"]').click();
    await expect(page.locator('#modeling-save-state')).toHaveText('已保存');
    await page.locator('[data-modeling-action="node"]').click();
    await form.locator('[name="modeling_grainDescription"]').fill('本窗口尚未保存的业务口径');
    await form.locator('[type="submit"]').click();
    await page.evaluate(async () => {
        const app = window.Pivot.legacy.PivotDataAnalysis, model = app.modeling.state.selected;
        await app.fetchJson(`${app.API}/models/${model.id}`, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ name: model.name, description: '另一个窗口修改', expectedVersion: model.version }) });
    });
    await page.locator('[data-modeling-action="save"]').click();
    await expect(page.locator('#modeling-save-state')).toContainText('保存失败');
    await expect(page.locator('#modeling-content')).toContainText('本窗口尚未保存的业务口径');
    const artifactRoot = path.resolve(__dirname, '../../output/bi-modeling'); await fs.mkdir(artifactRoot, { recursive: true });
    await page.screenshot({ path: path.join(artifactRoot, 'workspace-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('[data-modeling-action="node"]').click();
    const layout = await page.locator('.modeling-dialog').evaluate(node => { const rect = node.getBoundingClientRect(); return { left: rect.left, right: rect.right, width: window.innerWidth, scroll: node.scrollHeight, client: node.clientHeight }; });
    expect(layout.left).toBeGreaterThanOrEqual(0); expect(layout.right).toBeLessThanOrEqual(layout.width + 1);
    await page.screenshot({ path: path.join(artifactRoot, 'workspace-mobile.png'), fullPage: true });
    expect(errors).toEqual([]);
});
