'use strict';
/* global window, document, Event, requestAnimationFrame */
const { test, expect } = require('@playwright/test');
const fs = require('node:fs/promises');
const path = require('node:path');
const Zip = require('jszip');
const { execute } = require('../../server/db/client');
const { fixture } = require('../helpers/policy-review');

test('制度材料审查逐条显示双向依据，可修订、刷新恢复、下载Word并拒绝撤回后的下载', async ({ page }) => {
    test.setTimeout(120000);
    const source = await fixture();
    const login = await page.request.post('/api/auth/login', { data: { username: 'admin', password: process.env.DEFAULT_ADMIN_PASSWORD || 'E2eAdmin123' } });
    expect(login.ok()).toBeTruthy();
    const headers = { 'x-csrf-token': (await page.context().cookies()).find(cookie => cookie.name === 'pivot_csrf_token')?.value };
    const name = `制度审查模型${Date.now()}`;
    const created = await page.request.post('/api/models', { headers, data: { name, url: process.env.E2E_MODEL_URL, model_name: 'policy-review-e2e', context_window_tokens: 131072 } });
    expect(created.ok()).toBeTruthy();
    const models = await (await page.request.get('/api/models?limit=100')).json(), model = models.data.find(item => item.name === name);
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto('/chat');
    await expect(page.locator('#app')).toBeVisible();
    await page.evaluate(() => window.Pivot.moduleApi('workspaces.navigation').openAppsWorkbench({ app: 'regulations' }));
    await page.locator('#regulations-review-open-btn').click();
    await expect(page.locator('#policy-review-overlay')).toBeVisible();
    await page.locator('#policy-review-policy-query').fill('报销制度验收');
    await page.locator('[data-review-action="search"]').click();
    await page.locator(`[data-review-document="${source.documentId}"]`).check();
    await expect(page.locator(`#policy-review-model option[value="${model.id}"]`)).toBeAttached();
    await page.locator('#policy-review-model').selectOption(String(model.id));
    await page.locator('#policy-review-date').fill('2026-11-09');
    await page.locator('#policy-review-upload').setInputFiles({ name: '报销申请.txt', mimeType: 'text/plain', buffer: Buffer.from('本次报销金额为6200元。已取得部门负责人书面批准。', 'utf8') });
    await expect(page.locator('#policy-review-materials')).toContainText('报销申请.txt');
    const taskResponse = page.waitForResponse(response => response.url().endsWith('/api/apps/regulations/reviews') && response.request().method() === 'POST');
    await page.locator('#policy-review-start').click();
    const response = await taskResponse; expect(response.ok(), await response.text()).toBeTruthy();
    const id = (await response.json()).task.id;
    await expect(page.locator('#policy-review-detail')).toContainText('初审已结束', { timeout: 30000 });
    await expect(page.locator('#policy-review-detail [data-review-finding]')).toHaveCount(3);
    await expect(page.locator('#policy-review-detail')).toContainText('不符合');
    await expect(page.locator('#policy-review-detail')).toContainText('待核实');
    const first = page.locator('#policy-review-detail [data-review-finding]').first();
    await first.locator('[data-review-field="recommendation"]').fill('请补充例外审批依据并交业务负责人复核。');
    await page.locator('#policy-review-notes').fill('待补发票后再作最终决定。');
    await page.locator('[data-review-action="save"]').click();
    await expect(page.locator('#policy-review-detail')).toContainText('报告版本2');
    let releaseSave, savedOnServer;
    const waitingSave = new Promise(resolve => { savedOnServer = resolve; });
    const heldSave = new Promise(resolve => { releaseSave = resolve; });
    let holdSave = true;
    await page.route(`**/api/apps/regulations/reviews/${id}/report`, async route => {
        const response = await route.fetch();
        if (holdSave) { holdSave = false; savedOnServer(); await heldSave; }
        await route.fulfill({ response });
    });
    await page.locator('#policy-review-notes').fill('正在保存的一版备注。');
    await page.locator('[data-review-action="save"]').click();
    await waitingSave;
    await page.locator('#policy-review-notes').fill('保存期间追加的新备注仍须保留。');
    releaseSave();
    await expect(page.locator('#policy-review-message')).toContainText('保存期间的新修订仍保留');
    await expect(page.locator('#policy-review-notes')).toHaveValue('保存期间追加的新备注仍须保留。');
    await page.locator('[data-review-action="save"]').click();
    await expect(page.locator('#policy-review-detail')).toContainText('报告版本4');
    let releaseDetail, detailHeld;
    const heldDetail = new Promise(resolve => { detailHeld = resolve; });
    const releaseOldDetail = new Promise(resolve => { releaseDetail = resolve; });
    let holdDetail = true;
    await page.route(`**/api/apps/regulations/reviews/${id}`, async route => {
        if (route.request().method() !== 'GET' || !holdDetail) return route.continue();
        holdDetail = false;
        const response = await route.fetch(); detailHeld(); await releaseOldDetail; await route.fulfill({ response });
    });
    await page.locator(`[data-review-open="${id}"]`).click();
    await heldDetail;
    await page.locator('#policy-review-notes').fill('保存期间追加的新备注仍须保留。并已核对当前主体。');
    await page.locator('[data-review-action="save"]').click();
    await expect(page.locator('#policy-review-detail')).toContainText('报告版本5');
    releaseDetail();
    await expect(page.locator('#policy-review-notes')).toHaveValue('保存期间追加的新备注仍须保留。并已核对当前主体。');
    await page.locator('#policy-review-overlay .workspace-modal').screenshot({ path: path.resolve('.tmp/policy-review-desktop.png') });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('[data-review-action="export"]').scrollIntoViewIfNeeded();
    await expect(page.locator('[data-review-action="export"]')).toBeInViewport();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
    await page.screenshot({ path: path.resolve('.tmp/policy-review-mobile.png') });
    await page.setViewportSize({ width: 1440, height: 1000 });
    let holdExport, exportReady;
    const exportPrepared = new Promise(resolve => { exportReady = resolve; });
    const exportReleased = new Promise(resolve => { holdExport = resolve; });
    await page.route(`**/api/apps/regulations/reviews/${id}/export`, async route => {
        const response = await route.fetch(); exportReady(); await exportReleased; await route.fulfill({ response });
    });
    const exportResponse = page.waitForResponse(result => result.url().endsWith(`/reviews/${id}/export`) && result.request().method() === 'POST');
    const downloading = page.waitForEvent('download');
    await page.locator('[data-review-action="export"]').click();
    await exportPrepared;
    const sameVersionRefresh = page.waitForResponse(result => result.url().endsWith(`/reviews/${id}`) && result.request().method() === 'GET');
    await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')));
    await sameVersionRefresh;
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => resolve())));
    holdExport();
    const download = await downloading, delivered = await (await exportResponse).json();
    const buffer = await fs.readFile(await download.path()), zip = await Zip.loadAsync(buffer), xml = await zip.file('word/document.xml').async('string');
    expect(xml).toContain('6200'); expect(xml).toContain('业务负责人复核'); expect(xml).toContain('保存期间追加的新备注仍须保留');
    await fs.mkdir(path.resolve('.tmp/policy-review-acceptance'), { recursive: true }); await fs.writeFile(path.resolve('.tmp/policy-review-acceptance/browser.docx'), buffer);
    await page.reload();
    await expect(page.locator('#app')).toBeVisible();
    await page.evaluate(() => window.Pivot.moduleApi('workspaces.navigation').openAppsWorkbench({ app: 'regulations' }));
    await page.locator('#regulations-review-open-btn').click();
    await page.locator(`[data-review-open="${id}"]`).click();
    await expect(page.locator('#policy-review-notes')).toHaveValue('保存期间追加的新备注仍须保留。并已核对当前主体。');
    const currentHeaders = { 'x-csrf-token': (await page.context().cookies()).find(cookie => cookie.name === 'pivot_csrf_token')?.value };
    await page.request.delete(`/api/apps/regulations/reviews/${id}`, { headers: currentHeaders });
    expect((await page.request.post(`/api/agents/renditions/${delivered.delivery.renditionId}/download-token`, { headers: currentHeaders, data: {} })).status()).toBe(403);
    await page.evaluate(() => window.Pivot.moduleApi('apps.policyReview').reset());
    await expect(page.locator('#policy-review-overlay')).toHaveCount(0);
    await page.locator('#regulations-review-open-btn').click();
    await expect(page.locator('#policy-review-overlay')).toBeVisible();
    await page.locator('[data-review-action="close"]').press('Shift+Tab');
    await expect(page.locator('#policy-review-overlay')).toBeVisible();
    await page.keyboard.press('Escape');
    await expect(page.locator('#policy-review-overlay')).toBeHidden();
    await execute('UPDATE regulation_documents SET status=\'archived\' WHERE id=?', [source.documentId]);
});
