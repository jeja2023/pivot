'use strict';
/* global window, document */
const { test, expect } = require('@playwright/test');
const fs = require('node:fs/promises');
const path = require('node:path');
const JSZip = require('jszip');

test('分析图表直接生成可编辑汇报，刷新恢复并下载原生PPTX，桌面与窄屏可操作', async ({ page }) => {
    test.setTimeout(120000);
    test.skip(process.env.PIVOT_E2E_ISOLATED !== 'true', '需要隔离测试环境');
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto('/chat');
    await page.locator('#username').fill('admin');
    await page.locator('#password').fill(process.env.DEFAULT_ADMIN_PASSWORD || 'E2eAdmin123');
    await page.locator('#auth-submit').click();
    await expect(page.locator('#auth-container')).toBeHidden();
    await page.evaluate(() => window.Pivot.moduleApi('workspaces.navigation').openAppsWorkbench({ app: 'data-analysis' }));
    await page.locator('#data-analysis-file').setInputFiles({ name: '区域销售汇报.csv', mimeType: 'text/csv', buffer: Buffer.from('区域,收入\n华东,120\n华南,180\n华东,30\n', 'utf8') });
    await expect(page.locator('#data-analysis-dataset-table-body')).toContainText('区域销售汇报');
    await page.locator('[data-data-analysis-tab="chart"]').click();
    await page.locator('#data-analysis-chart-dataset').selectOption({ label: '区域销售汇报' });
    await page.locator('#data-analysis-chart-x').selectOption('c_1');
    await page.locator('#data-analysis-chart-y').selectOption('c_2');
    await page.locator('#data-analysis-chart-aggregation').selectOption('sum');
    await page.locator('#data-analysis-build-chart').click();
    await expect(page.locator('#data-analysis-chart-presentation')).toBeEnabled();
    await page.screenshot({ path: path.resolve(__dirname, '../../.tmp/analysis-report-chart-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#data-analysis-chart-presentation').scrollIntoViewIfNeeded();
    await expect(page.locator('#data-analysis-chart-presentation')).toBeVisible();
    await expect(page.locator('#data-analysis-chart-presentation')).toBeInViewport();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
    await page.screenshot({ path: path.resolve(__dirname, '../../.tmp/analysis-report-chart-mobile.png'), fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    const creation = page.waitForResponse(response => response.url().endsWith('/api/apps/presentations/from-analysis') && response.request().method() === 'POST');
    await page.locator('#data-analysis-chart-presentation').click();
    const response = await creation;
    expect(response.ok(), await response.text()).toBeTruthy();
    const { presentation } = await response.json();
    await expect(page.locator('#presentation-editor')).toBeVisible();
    await expect(page.locator('#presentation-slide-list [data-presentation-slide-id]')).toHaveCount(4);
    const chart = presentation.content.slides.flatMap(slide => slide.elements).find(element => element.type === 'chart');
    expect(chart.data.rows).toEqual([['华南', 180], ['华东', 150]]);
    expect(presentation.content.sources[0].analysisBinding.sourceVersion).toBe(1);
    await page.screenshot({ path: path.resolve(__dirname, '../../.tmp/analysis-report-presentation-desktop.png'), fullPage: true });
    await page.locator('#presentation-slide-list [data-presentation-slide-id]').nth(2).click();
    await page.locator('#presentation-stage').evaluate(element => Promise.all(element.getAnimations().map(animation => animation.finished.catch(() => {}))));
    await page.screenshot({ path: path.resolve(__dirname, '../../.tmp/analysis-report-slide-chart.png'), fullPage: true });
    await page.locator('#presentation-slide-list [data-presentation-slide-id]').nth(1).click();
    await page.locator('#presentation-stage').evaluate(element => Promise.all(element.getAnimations().map(animation => animation.finished.catch(() => {}))));
    await page.screenshot({ path: path.resolve(__dirname, '../../.tmp/analysis-report-slide-summary.png'), fullPage: true });
    await page.reload();
    await expect(page.locator('#auth-container')).toBeHidden();
    await page.evaluate(id => window.Pivot.moduleApi('workspaces.navigation').openAppsWorkbench({ app: 'presentations', presentationId: id }), presentation.id);
    await expect(page.locator('#presentation-editor')).toBeVisible();
    await expect(page.locator('#presentation-slide-list [data-presentation-slide-id]')).toHaveCount(4);
    await page.locator('#presentation-export-dropdown summary').click();
    const download = page.waitForEvent('download');
    await page.locator('#presentation-export-pptx-btn').click();
    const file = await download;
    const zip = await JSZip.loadAsync(await fs.readFile(await file.path()));
    expect(Object.keys(zip.files).filter(name => /^ppt\/charts\/chart\d+\.xml$/.test(name))).toHaveLength(1);
    expect(Object.keys(zip.files).filter(name => /^ppt\/slides\/slide\d+\.xml$/.test(name))).toHaveLength(4);
    expect(errors).toEqual([]);
});
