/* global window */
'use strict';

const { test, expect } = require('@playwright/test');
const path = require('node:path');
const fs = require('node:fs/promises');

test('后台分批导入在概览打开统一弹窗，上传、后台状态和完整数据集查看可用', async ({ page }) => {
    test.setTimeout(90000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto('/chat', { waitUntil: 'domcontentloaded' });
    await page.waitForLoadState('load', { timeout: 15000 });
    if (await page.locator('#username').isVisible()) {
        await page.locator('#username').fill('admin');
        await page.locator('#password').fill(process.env.DEFAULT_ADMIN_PASSWORD || 'E2eAdmin123');
        await page.locator('#auth-submit').click();
    }
    await expect(page.locator('#auth-container')).toBeHidden({ timeout: 15000 });
    await page.evaluate(() => window.Pivot.moduleApi('workspaces.navigation').openAppsWorkbench?.());
    await expect(page.locator('#apps-workbench-modal')).toBeVisible({ timeout: 15000 });
    await page.evaluate(async () => { await window.Pivot.loadScriptOnce('/chat/apps-workbench-data-analysis.js'); await window.Pivot.legacy.showDataAnalysisApp({ tab: 'overview' }); });
    await page.locator('#data-analysis-controlled-ingestion').click();
    const modal = page.locator('#data-analysis-modeling-dialog'), form = page.locator('#modeling-dialog-form');
    await expect(modal).toBeVisible();
    await expect(page.locator('#data-analysis-overview-panel')).toBeVisible();
    await form.locator('[name="ingestion_file"]').setInputFiles({ name: 'controlled-browser.csv', mimeType: 'text/csv', buffer: Buffer.from('订单号,金额,说明\r\n00001,100.01,"包含,逗号"\r\n00002,20.50,"包含\n换行"\r\n') });
    await form.locator('[name="ingestion_name"]').fill('浏览器后台完整导入');
    await form.locator('[name="ingestion_rows"]').fill('2');
    await form.locator('[name="ingestion_source_batch"]').fill('浏览器共同批次202611');
    await form.locator('[name="ingestion_source_period"]').fill('2026-11');
    const dataCutoff = new Date(Date.now() - 60000).toISOString();
    await form.locator('[name="ingestion_source_cutoff"]').fill(dataCutoff);
    await form.locator('[type="submit"]').click();
    await expect(modal).toBeHidden({ timeout: 30000 });
    await page.locator('#data-analysis-controlled-ingestion').click();
    const row = page.locator('#ingestion-task-table tr').filter({ hasText: '浏览器后台完整导入' });
    await expect(row).toContainText('已完成', { timeout: 30000 });
    await row.locator('[data-ingestion-open]').click();
    await expect(modal).toBeHidden();
    await expect(page.locator('#data-analysis-dataset-table-body')).toContainText('浏览器后台完整导入', { timeout: 10000 });
    await page.locator('#data-analysis-controlled-ingestion').click();
    await expect(page.locator('#ingestion-task-table')).toContainText('已完成');
    await page.setViewportSize({ width: 390, height: 844 });
    const layout = await page.locator('.modeling-dialog').evaluate(node => { const rect = node.getBoundingClientRect(); return { left: rect.left, right: rect.right, width: window.innerWidth }; });
    expect(layout.left).toBeGreaterThanOrEqual(0); expect(layout.right).toBeLessThanOrEqual(layout.width + 1);
    const root = path.resolve(__dirname, '../../output/bi-modeling'); await fs.mkdir(root, { recursive: true });
    await page.screenshot({ path: path.join(root, 'controlled-ingestion-mobile.png'), fullPage: true });
    await modal.locator('[data-modeling-action="close-dialog"]').first().click();
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator('[data-data-analysis-tab="governance"]').click();
    await page.locator('#data-analysis-governance-dataset').selectOption({ label: '浏览器后台完整导入' });
    await page.locator('#data-analysis-source-metadata').click();
    await expect(page.locator('#modeling-dialog-title')).toHaveText('来源业务信息');
    await expect(form.locator('[name="source_metadata_batch"]')).toHaveValue('浏览器共同批次202611');
    await expect(form.locator('[name="source_metadata_period"]')).toHaveValue('2026-11');
    await expect(form.locator('[name="source_metadata_cutoff"]')).toHaveValue(dataCutoff);
    await form.locator('[name="source_metadata_batch"]').fill('浏览器共同批次202611-补录');
    await form.locator('[name="source_metadata_cutoff"]').fill('');
    await form.locator('[type="submit"]').click();
    await expect(modal).toBeHidden();
    await page.locator('#data-analysis-source-metadata').click();
    await expect(form.locator('[name="source_metadata_batch"]')).toHaveValue('浏览器共同批次202611-补录');
    await expect(form.locator('[name="source_metadata_cutoff"]')).toHaveValue(dataCutoff);
    await expect(page.locator('#modeling-dialog-body')).toContainText('当前来源修订 2');
    await page.screenshot({ path: path.join(root, 'source-metadata-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    const sourceLayout = await page.locator('.modeling-dialog').evaluate(node => ({ width: window.innerWidth, right: node.getBoundingClientRect().right, scroll: node.scrollWidth, client: node.clientWidth }));
    expect(sourceLayout.right).toBeLessThanOrEqual(sourceLayout.width + 1); expect(sourceLayout.scroll).toBeLessThanOrEqual(sourceLayout.client + 1);
    await page.screenshot({ path: path.join(root, 'source-metadata-mobile.png'), fullPage: true });
    await modal.locator('[data-modeling-action="close-dialog"]').first().click();
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator('#data-analysis-open-scale-modal').click();
    await page.locator('#data-analysis-scale-dataset').selectOption({ label: '浏览器后台完整导入' });
    await page.locator('#data-analysis-scale-increment-batch').fill('浏览器追加批次1');
    const increment = { name: 'controlled-browser-increment.csv', mimeType: 'text/csv', buffer: Buffer.from('订单号,金额,说明\n00003,5.25,新增一笔\n') };
    await page.locator('#data-analysis-scale-increment-file').setInputFiles(increment);
    const appended = page.waitForResponse(response => response.url().endsWith('/increments') && response.request().method() === 'POST');
    await page.locator('#data-analysis-scale-append').click();
    const firstBatch = await (await appended).json();
    expect(firstBatch.success).toBe(true); expect(firstBatch.totalRows).toBe(3); expect(firstBatch.reused).toBe(false);
    await expect(page.locator('#data-analysis-scale-status')).toContainText('v3');
    await page.locator('#data-analysis-scale-increment-file').setInputFiles(increment);
    const repeated = page.waitForResponse(response => response.url().endsWith('/increments') && response.request().method() === 'POST');
    await page.locator('#data-analysis-scale-append').click();
    const sameBatch = await (await repeated).json();
    expect(sameBatch.reused).toBe(true); expect(sameBatch.totalRows).toBe(3); expect(sameBatch.sourceVersion).toBe(firstBatch.sourceVersion);
    await page.screenshot({ path: path.join(root, 'increment-batch-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(root, 'increment-batch-mobile.png'), fullPage: true });
    expect(errors).toEqual([]);
});
